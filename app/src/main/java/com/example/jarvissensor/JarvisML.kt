    // ----------------------------------------------
    // Logistic Regression intercept
    // ----------------------------------------------

    private val intercept: Double = 1.3745832057995941


    // ----------------------------------------------
    // Predict intent
    // ----------------------------------------------

    fun predict(text: String): String {

        // Convert text to lowercase
        val cleanText = text.lowercase()


        // ------------------------------------------
        // Tokenize text
        // ------------------------------------------

        val tokens = cleanText
            .split(Regex("\\W+"))
            .filter { it.isNotEmpty() }


        // ------------------------------------------
        // Term Frequency
        // ------------------------------------------

        val termFrequency = DoubleArray(vocabulary.size)


        for (token in tokens) {

            val index = vocabulary[token]

            if (index != null) {
                termFrequency[index] += 1.0
            }
        }


        // ------------------------------------------
        // TF-IDF
        // ------------------------------------------

        val tfidf = DoubleArray(vocabulary.size)

        for (i in termFrequency.indices) {
            tfidf[i] = termFrequency[i] * idf[i]
        }


        // ------------------------------------------
        // L2 normalization
        // ------------------------------------------

        var sumSquares = 0.0

        for (value in tfidf) {
            sumSquares += value * value
        }


        val norm = sqrt(sumSquares)


        if (norm > 0.0) {
            for (i in tfidf.indices) {
                tfidf[i] /= norm
            }
        }


        // ------------------------------------------
        // Logistic Regression
        // ------------------------------------------

        var score = intercept

        for (i in weights.indices) {
            score += weights[i] * tfidf[i]
        }


        // ------------------------------------------
        // Sigmoid
        // ------------------------------------------

        val probability = 1.0 / (1.0 + exp(-score))


        // ------------------------------------------
        // IMPORTANT:
        //
        // sklearn classes:
        // ['ANSWER_CALL', 'UNKNOWN']
        //
        // coef_[0] represents the second class.
        // Therefore:
        //
        // probability >= 0.5 -> UNKNOWN
        // probability <  0.5 -> ANSWER_CALL
        // ------------------------------------------

        return if (probability >= 0.5) {
            "UNKNOWN"
        } else {
            "ANSWER_CALL"
        }
    }
